typedef __gnuc_va_list va_list;
int
fiprintf(FILE * fp, const char *fmt,...)







{
  int ret;
  va_list ap;


  __builtin_va_start(ap,fmt);



  ret = vfiprintf (fp, fmt, ap);
  __builtin_va_end(ap);
  return ret;
}
